CREATE TABLE IF NOT EXISTS STRAVA.OPS.OAUTH_TOKEN (
  ATHLETE_ID STRING NOT NULL,
  REFRESH_TOKEN STRING NOT NULL,
  ACCESS_TOKEN STRING,
  EXPIRES_AT TIMESTAMP_NTZ,
  SCOPE STRING,
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ATHLETE_ID)
);

CREATE TABLE IF NOT EXISTS STRAVA.OPS.SYNC_STATE (
  STATE_KEY STRING NOT NULL,
  STATE_VALUE STRING,
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (STATE_KEY)
);

CREATE TABLE IF NOT EXISTS STRAVA.OPS.SYNC_QUEUE (
  ENDPOINT_KEY STRING NOT NULL,
  RESOURCE_ID STRING NOT NULL,
  PRIORITY NUMBER NOT NULL,
  STATUS STRING NOT NULL DEFAULT 'pending',
  ATTEMPTS NUMBER NOT NULL DEFAULT 0,
  LAST_ERROR STRING,
  ENQUEUED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ENDPOINT_KEY, RESOURCE_ID)
);

CREATE TABLE IF NOT EXISTS STRAVA.OPS.API_CALL_LOG (
  CALLED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  METHOD STRING,
  PATH STRING,
  STATUS_CODE NUMBER,
  READ_USAGE_15M NUMBER,
  READ_USAGE_DAY NUMBER,
  ERROR_MESSAGE STRING
);
