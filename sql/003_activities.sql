-- Typed activities table for the List Athlete Activities payload
-- (Documents/Strava Activities Table.json).
-- STRAVA.RAW.ACTIVITIES keeps the original JSON. This table is the queryable endpoint.

CREATE SCHEMA IF NOT EXISTS STRAVA.MART;

CREATE TABLE IF NOT EXISTS STRAVA.MART.ACTIVITIES (
  ACTIVITY_ID NUMBER NOT NULL,
  ACTIVITY_ID_STR VARCHAR,
  RESOURCE_STATE NUMBER,
  ATHLETE_ID NUMBER,
  ATHLETE_ID_STR VARCHAR,
  ATHLETE_RESOURCE_STATE NUMBER,
  NAME VARCHAR,
  DISTANCE FLOAT,
  MOVING_TIME NUMBER,
  ELAPSED_TIME NUMBER,
  TOTAL_ELEVATION_GAIN FLOAT,
  ACTIVITY_TYPE VARCHAR COMMENT 'JSON key: type',
  SPORT_TYPE VARCHAR,
  WORKOUT_TYPE NUMBER,
  DEVICE_NAME VARCHAR,
  TAGS VARIANT,
  START_DATE TIMESTAMP_NTZ,
  START_DATE_LOCAL TIMESTAMP_NTZ,
  TIMEZONE VARCHAR,
  UTC_OFFSET FLOAT,
  LOCATION_CITY VARCHAR,
  LOCATION_STATE VARCHAR,
  LOCATION_COUNTRY VARCHAR,
  ACHIEVEMENT_COUNT NUMBER,
  KUDOS_COUNT NUMBER,
  COMMENT_COUNT NUMBER,
  ATHLETE_COUNT NUMBER,
  PHOTO_COUNT NUMBER,
  MAP_ID VARCHAR,
  MAP_SUMMARY_POLYLINE VARCHAR,
  MAP_RESOURCE_STATE NUMBER,
  TRAINER BOOLEAN,
  COMMUTE BOOLEAN,
  MANUAL BOOLEAN,
  PRIVATE BOOLEAN,
  VISIBILITY VARCHAR,
  FLAGGED BOOLEAN,
  GEAR_ID VARCHAR,
  START_LATITUDE FLOAT COMMENT 'JSON key: start_latlng[0]',
  START_LONGITUDE FLOAT COMMENT 'JSON key: start_latlng[1]',
  END_LATITUDE FLOAT COMMENT 'JSON key: end_latlng[0]',
  END_LONGITUDE FLOAT COMMENT 'JSON key: end_latlng[1]',
  AVERAGE_SPEED FLOAT,
  MAX_SPEED FLOAT,
  AVERAGE_CADENCE FLOAT,
  AVERAGE_TEMP NUMBER,
  AVERAGE_WATTS FLOAT,
  MAX_WATTS NUMBER,
  WEIGHTED_AVERAGE_WATTS NUMBER,
  DEVICE_WATTS BOOLEAN,
  KILOJOULES FLOAT,
  HAS_HEARTRATE BOOLEAN,
  AVERAGE_HEARTRATE FLOAT,
  MAX_HEARTRATE FLOAT,
  HEARTRATE_OPT_OUT BOOLEAN,
  DISPLAY_HIDE_HEARTRATE_OPTION BOOLEAN,
  ELEV_HIGH FLOAT,
  ELEV_LOW FLOAT,
  UPLOAD_ID NUMBER,
  UPLOAD_ID_STR VARCHAR,
  EXTERNAL_ID VARCHAR,
  FROM_ACCEPTED_TAG BOOLEAN,
  PR_COUNT NUMBER,
  TOTAL_PHOTO_COUNT NUMBER,
  HAS_KUDOED BOOLEAN,
  SUFFER_SCORE FLOAT,
  INGESTED_AT TIMESTAMP_NTZ,
  PRIMARY KEY (ACTIVITY_ID)
);

MERGE INTO STRAVA.MART.ACTIVITIES AS TARGET
USING (
  SELECT
    PAYLOAD:id::NUMBER AS ACTIVITY_ID,
    PAYLOAD:id_str::VARCHAR AS ACTIVITY_ID_STR,
    PAYLOAD:resource_state::NUMBER AS RESOURCE_STATE,
    PAYLOAD:athlete:id::NUMBER AS ATHLETE_ID,
    PAYLOAD:athlete:id_str::VARCHAR AS ATHLETE_ID_STR,
    PAYLOAD:athlete:resource_state::NUMBER AS ATHLETE_RESOURCE_STATE,
    PAYLOAD:name::VARCHAR AS NAME,
    PAYLOAD:distance::FLOAT AS DISTANCE,
    PAYLOAD:moving_time::NUMBER AS MOVING_TIME,
    PAYLOAD:elapsed_time::NUMBER AS ELAPSED_TIME,
    PAYLOAD:total_elevation_gain::FLOAT AS TOTAL_ELEVATION_GAIN,
    PAYLOAD:type::VARCHAR AS ACTIVITY_TYPE,
    PAYLOAD:sport_type::VARCHAR AS SPORT_TYPE,
    PAYLOAD:workout_type::NUMBER AS WORKOUT_TYPE,
    PAYLOAD:device_name::VARCHAR AS DEVICE_NAME,
    PAYLOAD:tags AS TAGS,
    TRY_TO_TIMESTAMP_NTZ(PAYLOAD:start_date::VARCHAR) AS START_DATE,
    TRY_TO_TIMESTAMP_NTZ(PAYLOAD:start_date_local::VARCHAR) AS START_DATE_LOCAL,
    PAYLOAD:timezone::VARCHAR AS TIMEZONE,
    PAYLOAD:utc_offset::FLOAT AS UTC_OFFSET,
    PAYLOAD:location_city::VARCHAR AS LOCATION_CITY,
    PAYLOAD:location_state::VARCHAR AS LOCATION_STATE,
    PAYLOAD:location_country::VARCHAR AS LOCATION_COUNTRY,
    PAYLOAD:achievement_count::NUMBER AS ACHIEVEMENT_COUNT,
    PAYLOAD:kudos_count::NUMBER AS KUDOS_COUNT,
    PAYLOAD:comment_count::NUMBER AS COMMENT_COUNT,
    PAYLOAD:athlete_count::NUMBER AS ATHLETE_COUNT,
    PAYLOAD:photo_count::NUMBER AS PHOTO_COUNT,
    PAYLOAD:map:id::VARCHAR AS MAP_ID,
    PAYLOAD:map:summary_polyline::VARCHAR AS MAP_SUMMARY_POLYLINE,
    PAYLOAD:map:resource_state::NUMBER AS MAP_RESOURCE_STATE,
    PAYLOAD:trainer::BOOLEAN AS TRAINER,
    PAYLOAD:commute::BOOLEAN AS COMMUTE,
    PAYLOAD:manual::BOOLEAN AS MANUAL,
    PAYLOAD:private::BOOLEAN AS PRIVATE,
    PAYLOAD:visibility::VARCHAR AS VISIBILITY,
    PAYLOAD:flagged::BOOLEAN AS FLAGGED,
    PAYLOAD:gear_id::VARCHAR AS GEAR_ID,
    PAYLOAD:start_latlng[0]::FLOAT AS START_LATITUDE,
    PAYLOAD:start_latlng[1]::FLOAT AS START_LONGITUDE,
    PAYLOAD:end_latlng[0]::FLOAT AS END_LATITUDE,
    PAYLOAD:end_latlng[1]::FLOAT AS END_LONGITUDE,
    PAYLOAD:average_speed::FLOAT AS AVERAGE_SPEED,
    PAYLOAD:max_speed::FLOAT AS MAX_SPEED,
    PAYLOAD:average_cadence::FLOAT AS AVERAGE_CADENCE,
    PAYLOAD:average_temp::NUMBER AS AVERAGE_TEMP,
    PAYLOAD:average_watts::FLOAT AS AVERAGE_WATTS,
    PAYLOAD:max_watts::NUMBER AS MAX_WATTS,
    PAYLOAD:weighted_average_watts::NUMBER AS WEIGHTED_AVERAGE_WATTS,
    PAYLOAD:device_watts::BOOLEAN AS DEVICE_WATTS,
    PAYLOAD:kilojoules::FLOAT AS KILOJOULES,
    PAYLOAD:has_heartrate::BOOLEAN AS HAS_HEARTRATE,
    PAYLOAD:average_heartrate::FLOAT AS AVERAGE_HEARTRATE,
    PAYLOAD:max_heartrate::FLOAT AS MAX_HEARTRATE,
    PAYLOAD:heartrate_opt_out::BOOLEAN AS HEARTRATE_OPT_OUT,
    PAYLOAD:display_hide_heartrate_option::BOOLEAN AS DISPLAY_HIDE_HEARTRATE_OPTION,
    PAYLOAD:elev_high::FLOAT AS ELEV_HIGH,
    PAYLOAD:elev_low::FLOAT AS ELEV_LOW,
    PAYLOAD:upload_id::NUMBER AS UPLOAD_ID,
    PAYLOAD:upload_id_str::VARCHAR AS UPLOAD_ID_STR,
    PAYLOAD:external_id::VARCHAR AS EXTERNAL_ID,
    PAYLOAD:from_accepted_tag::BOOLEAN AS FROM_ACCEPTED_TAG,
    PAYLOAD:pr_count::NUMBER AS PR_COUNT,
    PAYLOAD:total_photo_count::NUMBER AS TOTAL_PHOTO_COUNT,
    PAYLOAD:has_kudoed::BOOLEAN AS HAS_KUDOED,
    PAYLOAD:suffer_score::FLOAT AS SUFFER_SCORE,
    INGESTED_AT
  FROM STRAVA.RAW.ACTIVITIES
  WHERE DELETED_AT IS NULL
    AND PAYLOAD IS NOT NULL
) AS SOURCE
ON TARGET.ACTIVITY_ID = SOURCE.ACTIVITY_ID
WHEN MATCHED THEN UPDATE SET
  ACTIVITY_ID_STR = SOURCE.ACTIVITY_ID_STR,
  RESOURCE_STATE = SOURCE.RESOURCE_STATE,
  ATHLETE_ID = SOURCE.ATHLETE_ID,
  ATHLETE_ID_STR = SOURCE.ATHLETE_ID_STR,
  ATHLETE_RESOURCE_STATE = SOURCE.ATHLETE_RESOURCE_STATE,
  NAME = SOURCE.NAME,
  DISTANCE = SOURCE.DISTANCE,
  MOVING_TIME = SOURCE.MOVING_TIME,
  ELAPSED_TIME = SOURCE.ELAPSED_TIME,
  TOTAL_ELEVATION_GAIN = SOURCE.TOTAL_ELEVATION_GAIN,
  ACTIVITY_TYPE = SOURCE.ACTIVITY_TYPE,
  SPORT_TYPE = SOURCE.SPORT_TYPE,
  WORKOUT_TYPE = SOURCE.WORKOUT_TYPE,
  DEVICE_NAME = SOURCE.DEVICE_NAME,
  TAGS = SOURCE.TAGS,
  START_DATE = SOURCE.START_DATE,
  START_DATE_LOCAL = SOURCE.START_DATE_LOCAL,
  TIMEZONE = SOURCE.TIMEZONE,
  UTC_OFFSET = SOURCE.UTC_OFFSET,
  LOCATION_CITY = SOURCE.LOCATION_CITY,
  LOCATION_STATE = SOURCE.LOCATION_STATE,
  LOCATION_COUNTRY = SOURCE.LOCATION_COUNTRY,
  ACHIEVEMENT_COUNT = SOURCE.ACHIEVEMENT_COUNT,
  KUDOS_COUNT = SOURCE.KUDOS_COUNT,
  COMMENT_COUNT = SOURCE.COMMENT_COUNT,
  ATHLETE_COUNT = SOURCE.ATHLETE_COUNT,
  PHOTO_COUNT = SOURCE.PHOTO_COUNT,
  MAP_ID = SOURCE.MAP_ID,
  MAP_SUMMARY_POLYLINE = SOURCE.MAP_SUMMARY_POLYLINE,
  MAP_RESOURCE_STATE = SOURCE.MAP_RESOURCE_STATE,
  TRAINER = SOURCE.TRAINER,
  COMMUTE = SOURCE.COMMUTE,
  MANUAL = SOURCE.MANUAL,
  PRIVATE = SOURCE.PRIVATE,
  VISIBILITY = SOURCE.VISIBILITY,
  FLAGGED = SOURCE.FLAGGED,
  GEAR_ID = SOURCE.GEAR_ID,
  START_LATITUDE = SOURCE.START_LATITUDE,
  START_LONGITUDE = SOURCE.START_LONGITUDE,
  END_LATITUDE = SOURCE.END_LATITUDE,
  END_LONGITUDE = SOURCE.END_LONGITUDE,
  AVERAGE_SPEED = SOURCE.AVERAGE_SPEED,
  MAX_SPEED = SOURCE.MAX_SPEED,
  AVERAGE_CADENCE = SOURCE.AVERAGE_CADENCE,
  AVERAGE_TEMP = SOURCE.AVERAGE_TEMP,
  AVERAGE_WATTS = SOURCE.AVERAGE_WATTS,
  MAX_WATTS = SOURCE.MAX_WATTS,
  WEIGHTED_AVERAGE_WATTS = SOURCE.WEIGHTED_AVERAGE_WATTS,
  DEVICE_WATTS = SOURCE.DEVICE_WATTS,
  KILOJOULES = SOURCE.KILOJOULES,
  HAS_HEARTRATE = SOURCE.HAS_HEARTRATE,
  AVERAGE_HEARTRATE = SOURCE.AVERAGE_HEARTRATE,
  MAX_HEARTRATE = SOURCE.MAX_HEARTRATE,
  HEARTRATE_OPT_OUT = SOURCE.HEARTRATE_OPT_OUT,
  DISPLAY_HIDE_HEARTRATE_OPTION = SOURCE.DISPLAY_HIDE_HEARTRATE_OPTION,
  ELEV_HIGH = SOURCE.ELEV_HIGH,
  ELEV_LOW = SOURCE.ELEV_LOW,
  UPLOAD_ID = SOURCE.UPLOAD_ID,
  UPLOAD_ID_STR = SOURCE.UPLOAD_ID_STR,
  EXTERNAL_ID = SOURCE.EXTERNAL_ID,
  FROM_ACCEPTED_TAG = SOURCE.FROM_ACCEPTED_TAG,
  PR_COUNT = SOURCE.PR_COUNT,
  TOTAL_PHOTO_COUNT = SOURCE.TOTAL_PHOTO_COUNT,
  HAS_KUDOED = SOURCE.HAS_KUDOED,
  SUFFER_SCORE = SOURCE.SUFFER_SCORE,
  INGESTED_AT = SOURCE.INGESTED_AT
WHEN NOT MATCHED THEN INSERT (
  ACTIVITY_ID, ACTIVITY_ID_STR, RESOURCE_STATE, ATHLETE_ID, ATHLETE_ID_STR,
  ATHLETE_RESOURCE_STATE, NAME, DISTANCE, MOVING_TIME, ELAPSED_TIME,
  TOTAL_ELEVATION_GAIN, ACTIVITY_TYPE, SPORT_TYPE, WORKOUT_TYPE, DEVICE_NAME, TAGS,
  START_DATE, START_DATE_LOCAL, TIMEZONE, UTC_OFFSET, LOCATION_CITY, LOCATION_STATE,
  LOCATION_COUNTRY, ACHIEVEMENT_COUNT, KUDOS_COUNT, COMMENT_COUNT, ATHLETE_COUNT,
  PHOTO_COUNT, MAP_ID, MAP_SUMMARY_POLYLINE, MAP_RESOURCE_STATE, TRAINER, COMMUTE,
  MANUAL, PRIVATE, VISIBILITY, FLAGGED, GEAR_ID, START_LATITUDE, START_LONGITUDE,
  END_LATITUDE, END_LONGITUDE, AVERAGE_SPEED, MAX_SPEED, AVERAGE_CADENCE, AVERAGE_TEMP,
  AVERAGE_WATTS, MAX_WATTS, WEIGHTED_AVERAGE_WATTS, DEVICE_WATTS, KILOJOULES,
  HAS_HEARTRATE, AVERAGE_HEARTRATE, MAX_HEARTRATE, HEARTRATE_OPT_OUT,
  DISPLAY_HIDE_HEARTRATE_OPTION, ELEV_HIGH, ELEV_LOW, UPLOAD_ID, UPLOAD_ID_STR,
  EXTERNAL_ID, FROM_ACCEPTED_TAG, PR_COUNT, TOTAL_PHOTO_COUNT, HAS_KUDOED, SUFFER_SCORE,
  INGESTED_AT
) VALUES (
  SOURCE.ACTIVITY_ID, SOURCE.ACTIVITY_ID_STR, SOURCE.RESOURCE_STATE, SOURCE.ATHLETE_ID,
  SOURCE.ATHLETE_ID_STR, SOURCE.ATHLETE_RESOURCE_STATE, SOURCE.NAME, SOURCE.DISTANCE,
  SOURCE.MOVING_TIME, SOURCE.ELAPSED_TIME, SOURCE.TOTAL_ELEVATION_GAIN, SOURCE.ACTIVITY_TYPE,
  SOURCE.SPORT_TYPE, SOURCE.WORKOUT_TYPE, SOURCE.DEVICE_NAME, SOURCE.TAGS, SOURCE.START_DATE,
  SOURCE.START_DATE_LOCAL, SOURCE.TIMEZONE, SOURCE.UTC_OFFSET, SOURCE.LOCATION_CITY,
  SOURCE.LOCATION_STATE, SOURCE.LOCATION_COUNTRY, SOURCE.ACHIEVEMENT_COUNT, SOURCE.KUDOS_COUNT,
  SOURCE.COMMENT_COUNT, SOURCE.ATHLETE_COUNT, SOURCE.PHOTO_COUNT, SOURCE.MAP_ID,
  SOURCE.MAP_SUMMARY_POLYLINE, SOURCE.MAP_RESOURCE_STATE, SOURCE.TRAINER, SOURCE.COMMUTE,
  SOURCE.MANUAL, SOURCE.PRIVATE, SOURCE.VISIBILITY, SOURCE.FLAGGED, SOURCE.GEAR_ID,
  SOURCE.START_LATITUDE, SOURCE.START_LONGITUDE, SOURCE.END_LATITUDE, SOURCE.END_LONGITUDE,
  SOURCE.AVERAGE_SPEED, SOURCE.MAX_SPEED, SOURCE.AVERAGE_CADENCE, SOURCE.AVERAGE_TEMP,
  SOURCE.AVERAGE_WATTS, SOURCE.MAX_WATTS, SOURCE.WEIGHTED_AVERAGE_WATTS, SOURCE.DEVICE_WATTS,
  SOURCE.KILOJOULES, SOURCE.HAS_HEARTRATE, SOURCE.AVERAGE_HEARTRATE, SOURCE.MAX_HEARTRATE,
  SOURCE.HEARTRATE_OPT_OUT, SOURCE.DISPLAY_HIDE_HEARTRATE_OPTION, SOURCE.ELEV_HIGH,
  SOURCE.ELEV_LOW, SOURCE.UPLOAD_ID, SOURCE.UPLOAD_ID_STR, SOURCE.EXTERNAL_ID,
  SOURCE.FROM_ACCEPTED_TAG, SOURCE.PR_COUNT, SOURCE.TOTAL_PHOTO_COUNT, SOURCE.HAS_KUDOED,
  SOURCE.SUFFER_SCORE, SOURCE.INGESTED_AT
);

DELETE FROM STRAVA.MART.ACTIVITIES
WHERE ACTIVITY_ID IN (
  SELECT PAYLOAD:id::NUMBER
  FROM STRAVA.RAW.ACTIVITIES
  WHERE DELETED_AT IS NOT NULL
);
