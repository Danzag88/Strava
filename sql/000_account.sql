-- Run once as ACCOUNTADMIN before the first backup.
-- Replace REPLACE_WITH_PUBLIC_KEY with the base64 body of snowflake_key.pub
-- (the lines between BEGIN PUBLIC KEY and END PUBLIC KEY, joined into one line).

CREATE WAREHOUSE IF NOT EXISTS STRAVA_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS STRAVA;
CREATE SCHEMA IF NOT EXISTS STRAVA.RAW;
CREATE SCHEMA IF NOT EXISTS STRAVA.OPS;

CREATE ROLE IF NOT EXISTS STRAVA_BACKUP;

GRANT USAGE ON WAREHOUSE STRAVA_WH TO ROLE STRAVA_BACKUP;
GRANT USAGE ON DATABASE STRAVA TO ROLE STRAVA_BACKUP;
GRANT ALL PRIVILEGES ON SCHEMA STRAVA.RAW TO ROLE STRAVA_BACKUP;
GRANT ALL PRIVILEGES ON SCHEMA STRAVA.OPS TO ROLE STRAVA_BACKUP;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA STRAVA.RAW TO ROLE STRAVA_BACKUP;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA STRAVA.OPS TO ROLE STRAVA_BACKUP;

CREATE USER IF NOT EXISTS STRAVA_LOADER
  DEFAULT_ROLE = STRAVA_BACKUP
  DEFAULT_WAREHOUSE = STRAVA_WH
  DEFAULT_NAMESPACE = STRAVA.OPS
  RSA_PUBLIC_KEY = 'REPLACE_WITH_PUBLIC_KEY';

GRANT ROLE STRAVA_BACKUP TO USER STRAVA_LOADER;
